"""L=2,400 daily loss lock + +2,000 profit lock with the REAL AccountGuard per tick in the MT5 tester (MT5 broker real ticks, portable tester terminal): replay of the gold pair's trades (x1.5) from the MT5 broker pool
(PairReplay.mq5 + generated TradeList.mqh). Variants: no runner / SDB runner. python -m forex.self_improving.session.verify_guard_tick"""
import glob, shutil, subprocess, sys
from pathlib import Path
import numpy as np, pandas as pd
from forex.ea_batch import mt5data_run as ER
from forex.self_improving.session import session_sdbrunner as R, session_episode_combo as C

TR, TERM = ER.TR, ER.TERM_DIR; SRC = Path(r"D:\finance\beginner-quant-research\mt5\expert_advisors"); EXP = TERM / "MQL5" / "Experts" / "the trader"
import os
DSP = os.environ.get('DSP', '2.4')
TAG = 'L' + str(int(float(DSP) * 1000))
COLS = ["time", "event", "equity", "balance", "dayref", "positions", "detail"]


def write_list(t, m):
    q = t["q"] * m / 100.0; lots = np.round(q, 2); keep = lots >= 0.01; o = np.argsort(t["in_s"][keep], kind="stable")
    arr = lambda k, f: ",".join(f(x) for x in np.asarray(t[k])[keep][o])
    lots_s = ",".join(f"{x:.2f}" for x in lots[keep][o])
    txt = f"// generated by verify_guard_tick.py: {int(keep.sum())} trades\ndatetime T_OPEN[]={{{arr('in_s', lambda x: f'(datetime){int(x)}')}}};\ndatetime T_CLOSE[]={{{arr('out_s', lambda x: f'(datetime){int(x)}')}}};\nint T_SIDE[]={{{arr('side', lambda x: str(int(x)))}}};\ndouble T_LOTS[]={{{lots_s}}};\n"
    (EXP / "TradeList.mqh").write_text(txt, encoding="ascii")


def compile_ea():
    shutil.copy(SRC / "AccountGuard.mqh", EXP / "AccountGuard.mqh"); shutil.copy(SRC / "PairReplay.mq5", EXP / "PairReplay.mq5")
    log = EXP / "PairReplay.log"
    subprocess.run([str(TERM / "MetaEditor64.exe"), "/portable", f"/compile:{EXP / 'PairReplay.mq5'}", f"/log:{log}"], check=False, timeout=120)
    print(log.read_text(encoding="utf-16", errors="ignore").strip().splitlines()[-1], flush=True)


def read_log(name):
    f = max(glob.glob(str(TERM / "Tester" / "Agent-*" / "MQL5" / "Files" / name)), key=lambda p: Path(p).stat().st_mtime)
    d = pd.read_csv(f, header=None, names=COLS, on_bad_lines="skip"); d["time"] = pd.to_datetime(d["time"], format="%Y.%m.%d %H:%M:%S", errors="coerce"); return d.dropna(subset=["time"])


def main():
    tr, lo, hi = R.load_flag("MT5"); compile_ea(); rows = []
    for nm, t in (("no runner", tr), ("runner SDB", R.runner_leg(tr, 0, "sdb"))):
        write_list(t, 1.5); compile_ea()
        r = TR.run_test("pair_replay_" + TAG + "_" + nm.replace(" ", "_"), r"the trader\PairReplay.ex5", "XAUUSD+", "M1", "2025.10.01", "2026.09.30", {"InpDailyStopPct": DSP, "InpProfitCapPct": "2.0", "InpFloorStopPct": "6.5", "InpShiftSec": "0"}, timeout=14400)
        print(f"{nm}: net {r['net']:,.0f} | note {r['note']!r} | seconds {r['seconds']} | eq DD {r['eq_dd']}", flush=True)
        d = read_log("pair_replay.csv"); d.to_csv(f"D:/finance/si_ledgers/PAIRREPLAY_{TAG}_{nm.replace(' ', '_')}_log.csv", index=False)
        ev = d[d.event.isin(["DAYSTOP", "PROFITCAP", "EMERGENCY"])].copy(); ev["rel"] = ev.equity - ev.dayref; snap = d[d.event == "SNAP"].copy(); snap["rel"] = snap.equity - snap.dayref
        print(f"  events: PROFITCAP {int((ev.event == 'PROFITCAP').sum())}, DAYSTOP {int((ev.event == 'DAYSTOP').sum())}, EMERGENCY {int((ev.event == 'EMERGENCY').sum())}; worst equity vs day start balance {snap.rel.min():,.0f}; END {d[d.event == 'END'].detail.tolist()}")
        print(ev[["time", "event", "rel"]].assign(rel=lambda x: x.rel.round(0)).to_string(index=False), flush=True)
        rows.append(dict(variant=nm, net=r["net"], eq_dd=r["eq_dd"], profitcap=int((ev.event == "PROFITCAP").sum()), daystop=int((ev.event == "DAYSTOP").sum()), worst_rel=snap.rel.min()))
    pd.DataFrame(rows).to_csv(f"D:/finance/si_ledgers/PAIRREPLAY_{TAG}_summary.csv", index=False)


if __name__ == "__main__":
    main()
