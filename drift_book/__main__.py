"""Rerun the drift book on free data:  python -m drift_book  [--refresh]

Writes drift_book/results/RESULTS.md and drift_book/results/equity.png."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from drift_book import book, data

OUT = Path(__file__).parent / "results"
# The first period was never looked at during the original research; the others match its periods.
PERIODS = {
    "2010-19 (new, never tested)": ("2010-01-01", "2019-12-31"),
    "2020-21 (out-of-time)": ("2020-01-01", "2021-12-31"),
    "2022-24 (development)": ("2022-01-01", "2024-12-31"),
    "2025 (validation)": ("2025-01-01", "2025-12-31"),
    "2026 to date (hold-out)": ("2026-01-01", "2026-12-31"),
    "2010 to date": ("2010-01-01", "2026-12-31"),
}
COLUMNS = ("swap_free", "cfd_swap", "futures")


def table(runs: dict[str, pd.DataFrame]) -> str:
    lines = ["| book | period | " + " | ".join(f"{c} return" for c in COLUMNS) + " | Sharpe (swap-free) | max drawdown (swap-free) |",
             "|---|---|" + "---:|" * (len(COLUMNS) + 2)]
    for name, run in runs.items():
        for label, (a, b) in PERIODS.items():
            part = run.loc[a:b]
            s = {c: book.stats(part[c]) for c in COLUMNS}
            lines.append(f"| {name} | {label} | " + " | ".join(f"{s[c]['return']:+.1%}" for c in COLUMNS)
                         + f" | {s['swap_free']['sharpe']:.2f} | {s['swap_free']['max_dd']:.1%} |")
    return "\n".join(lines)


def chart(runs: dict[str, pd.DataFrame], path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(9, 4.5))
    run = runs["trend filter (D2)"].loc["2010-01-01":]
    for c in COLUMNS:
        ax.plot((1 + run[c]).cumprod(), label=f"trend filter, {c.replace('_', ' ')}", linewidth=1.2)
    base = runs["no filter (D1)"].loc["2010-01-01":, "swap_free"]
    ax.plot((1 + base).cumprod(), label="no filter, swap free", color="grey", linestyle="--", linewidth=1)
    ax.set_yscale("log")
    ax.set_yticks([1, 1.5, 2, 3, 4, 5])
    ax.yaxis.set_major_formatter(matplotlib.ticker.ScalarFormatter())
    ax.yaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.set_title("Drift book, growth of 1, free daily data")
    ax.legend()
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=110)


def main() -> None:
    prices, cash = data.load(refresh="--refresh" in sys.argv)
    runs = {
        "trend filter (D2)": book.backtest(prices, cash, trend_filter=True),
        "no filter (D1)": book.backtest(prices, cash, trend_filter=False),
    }
    OUT.mkdir(exist_ok=True)
    chart(runs, OUT / "equity.png")
    t = table(runs)
    first, last = prices.index[0].date(), prices.index[-1].date()
    (OUT / "RESULTS.md").write_text(
        f"# Drift book on free data\n\nGenerated by `python -m drift_book`. Data {first} to {last} (Yahoo Finance daily closes, in USD).\n"
        f"Returns are a year, compounded. Costs: {book.Costs()}.\n\n{t}\n\n![equity](equity.png)\n", encoding="utf-8")
    print(t)
    print(f"\nwrote {OUT / 'RESULTS.md'} and {OUT / 'equity.png'}")


if __name__ == "__main__":
    main()
